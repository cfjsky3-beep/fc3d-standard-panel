export function oddsText(game: string, name: string, option?: string) {
  if (game !== "ssc") return "";
  const odds = observedOdds[name] ?? {};
  if (option !== undefined) return odds[option]?.raw ?? "";
  const values = [...new Set(Object.values(odds).map(v=>v.raw))];
  if (!values.length) return "";
  if (values.length === 1) return values[0];
  if (values.some(v=>v.includes("/"))) return "分奖级，见投注项";
  const sorted = values.sort((a,b)=>Number(a)-Number(b));
  return `${sorted[0]}–${sorted.at(-1)}（已核对项）`;
}
